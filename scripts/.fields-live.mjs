import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto('https://netzwerky.pages.dev/read/a2-kb/28/', { waitUntil: 'networkidle' })
await p.waitForTimeout(900)
await p.click('button[aria-label="Antwortfeld setzen"]')
await p.waitForTimeout(200)
const boxes = await p.$$('button.absolute.rounded-sm')
console.log('boxes', boxes.length)
await boxes[2].click(); await p.waitForTimeout(200)
await boxes[5].click(); await p.waitForTimeout(300)
const inputs = await p.$$('input[placeholder="…"]')
console.log('fields', inputs.length)
if (inputs[0]) await inputs[0].fill('das Handy')
if (inputs[1]) await inputs[1].fill('blabla')
await p.waitForTimeout(150)
const pr = await p.$('button[aria-label="Prüfen"]')
if (pr) await pr.click()
await p.waitForTimeout(300)
console.log(JSON.stringify(await p.evaluate(() => [...document.querySelectorAll('input[placeholder="…"]')].map(i => getComputedStyle(i).borderColor))))
await p.screenshot({ path: '/tmp/shots/live-fields.png' })
await p.click('button[aria-label="Bibliothek"]'); await p.waitForTimeout(600)
await p.screenshot({ path: '/tmp/shots/live-drawer3.png' })
await b.close()
