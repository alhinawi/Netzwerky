import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto('http://localhost:8099/read/a2-kb/83/', { waitUntil: 'networkidle' }); await p.waitForTimeout(700)
const ins = await p.$$('input[aria-label]')
await ins[0].click({ force: true })
await p.keyboard.type('5')
await p.waitForTimeout(200)
console.log('before', JSON.stringify(await p.evaluate(() => [...document.querySelectorAll('input[aria-label]')].map(i=>i.value))))
await p.screenshot({ path: '/tmp/shots/reset-before.png' })
await p.evaluate(() => document.querySelector('button[aria-label="Zurücksetzen"]').click())
await p.waitForTimeout(400)
console.log('after', JSON.stringify(await p.evaluate(() => [...document.querySelectorAll('input[aria-label]')].map(i=>i.value))))
await p.screenshot({ path: '/tmp/shots/reset-after.png' })
await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(600)
console.log('reload', JSON.stringify(await p.evaluate(() => [...document.querySelectorAll('input[aria-label]')].map(i=>i.value))))
await b.close()
