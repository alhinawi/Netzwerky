import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto('http://localhost:8099/read/a1-kb/61/', { waitUntil: 'networkidle' }); await p.waitForTimeout(600)
await p.screenshot({ path: '/tmp/shots/burger.png' })
await p.click('button[aria-label="Bibliothek"]'); await p.waitForTimeout(500)
await p.screenshot({ path: '/tmp/shots/burger-drawer.png' })
await p.keyboard.press('Escape').catch(()=>{})
await p.click('button[aria-label="Schließen"]').catch(()=>{})
await p.waitForTimeout(300)
await p.click('button[aria-label="Profil"]'); await p.waitForTimeout(500)
await p.screenshot({ path: '/tmp/shots/profile-sheet.png' })
console.log(JSON.stringify(await p.evaluate(() => ({ sw: document.documentElement.scrollWidth }))))
await b.close()
