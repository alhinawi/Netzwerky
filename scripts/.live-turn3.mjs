import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto('https://netzwerky.pages.dev/read/a2-kb/66/', { waitUntil: 'networkidle' })
await p.waitForTimeout(600)
await p.evaluate(() => { const b = document.querySelector('button[aria-label="Nächste Seite"]'); b && b.click() })
await p.waitForTimeout(60)
await p.screenshot({ path: '/tmp/shots/turn-060.png' })
await p.waitForTimeout(90)
await p.screenshot({ path: '/tmp/shots/turn-150.png' })
await p.waitForTimeout(150)
await p.screenshot({ path: '/tmp/shots/turn-300.png' })
await p.waitForTimeout(400)
await p.screenshot({ path: '/tmp/shots/turn-done2.png' })
console.log('url', p.url())
await b.close()
