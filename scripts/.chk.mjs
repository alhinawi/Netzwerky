import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto('http://localhost:8099/read/a2-kb/28/', { waitUntil: 'networkidle' })
await p.waitForTimeout(700)
const cbs = await p.$$('button[aria-label^="Test Kasten"]')
console.log('checkboxes', cbs.length)
if (cbs[0]) await cbs[0].click()
if (cbs[1]) await cbs[1].click()
await p.waitForTimeout(200)
const pr = await p.$('button[aria-label="Prüfen"]'); if (pr) await pr.click()
await p.waitForTimeout(300)
console.log(JSON.stringify(await p.evaluate(() => [...document.querySelectorAll('button[aria-label^="Test Kasten"]')].map(x => [x.getAttribute('aria-pressed'), getComputedStyle(x).borderColor]))))
await p.screenshot({ path: '/tmp/shots/check-fields.png' })
await b.close()
