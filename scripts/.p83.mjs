import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto('http://localhost:8099/read/a2-kb/83/', { waitUntil: 'networkidle' })
await p.waitForTimeout(700)
const inputs = await p.$$('input[aria-label]')
console.log('fields', inputs.length)
if (inputs[0]) await inputs[0].fill('5')
if (inputs[1]) await inputs[1].fill('9')
await p.waitForTimeout(200)
await p.screenshot({ path: '/tmp/shots/p83-typed.png' })
const pr = await p.$('button[aria-label="Prüfen"]')
console.log('pruefen', !!pr)
if (pr) await pr.click()
await p.waitForTimeout(300)
console.log(JSON.stringify(await p.evaluate(() => [...document.querySelectorAll('input[aria-label]')].map(i => getComputedStyle(i).borderBottomColor))))
await p.screenshot({ path: '/tmp/shots/p83-checked.png' })
await b.close()
